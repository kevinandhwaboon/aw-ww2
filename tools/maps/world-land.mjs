// Turns the Natural Earth land outlines (the `world-atlas` package, public domain) into the
// coastlines the map-select world map draws (00-master-design §12). Run with
// `node tools/maps/world-land.mjs`; it writes src/ui/worldLand.ts, which is committed, so the game
// never loads the package itself.
//
// Each land ring becomes SVG path data in tenths of a degree: x = longitude × 10, y = −latitude × 10
// (a plain equirectangular projection), simplified so the file stays small.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const topo = JSON.parse(readFileSync(join(root, "node_modules", "world-atlas", "land-50m.json"), "utf8"));

/** Decodes TopoJSON's quantized, delta-encoded arcs into longitude/latitude points. */
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});
const arcPoints = (i) => (i >= 0 ? arcs[i] : arcs[~i].slice().reverse());
const ringOf = (indices) => indices.flatMap((i, n) => (n === 0 ? arcPoints(i) : arcPoints(i).slice(1)));

const rings = [];
const collect = (geometry) => {
  if (geometry.type === "GeometryCollection") geometry.geometries.forEach(collect);
  else if (geometry.type === "Polygon") geometry.arcs.forEach((r) => rings.push(ringOf(r)));
  else if (geometry.type === "MultiPolygon") geometry.arcs.forEach((p) => p.forEach((r) => rings.push(ringOf(r))));
};
collect(topo.objects.land);

/** Ramer–Douglas–Peucker, in degrees. */
function simplify(points, tolerance) {
  if (points.length < 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a], [bx, by] = points[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-9;
    let worst = -1, far = 0;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      const d = Math.abs(dy * (px - ax) - dx * (py - ay)) / len;
      if (d > far) [far, worst] = [d, i];
    }
    if (far > tolerance && worst > 0) {
      keep[worst] = 1;
      stack.push([a, worst], [worst, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const area = (pts) => Math.abs(pts.reduce((s, [x, y], i) => {
  const [nx, ny] = pts[(i + 1) % pts.length];
  return s + x * ny - nx * y;
}, 0)) / 2;

const paths = [];
let pointCount = 0;
for (const ring of rings) {
  // Antarctica and the Arctic ice are off the map; specks under ~1 km² never show.
  if (ring.every(([, lat]) => lat < -58)) continue;
  if (area(ring) < 0.004) continue;
  // A ring starts and ends on the same point, so it's simplified as two halves.
  const mid = Math.floor(ring.length / 2);
  const pts = [...simplify(ring.slice(0, mid + 1), 0.06), ...simplify(ring.slice(mid), 0.06).slice(1)].map(([lon, lat]) => [Math.round(lon * 10), Math.round(-lat * 10)]);
  const dedup = pts.filter((p, i) => i === 0 || p[0] !== pts[i - 1][0] || p[1] !== pts[i - 1][1]);
  if (dedup.length < 3) continue;
  pointCount += dedup.length;
  let d = `M${dedup[0][0]} ${dedup[0][1]}l`;
  for (let i = 1; i < dedup.length; i++) {
    const dx = dedup[i][0] - dedup[i - 1][0], dy = dedup[i][1] - dedup[i - 1][1];
    d += `${i > 1 && dx >= 0 ? " " : ""}${dx}${dy >= 0 ? " " : ""}${dy}`;
  }
  paths.push(d + "z");
}

const out = `// Generated by tools/maps/world-land.mjs from Natural Earth 1:50m land (public domain, via the
// world-atlas package). Don't edit by hand. SVG path data in tenths of a degree: x = longitude × 10,
// y = −latitude × 10.

export const WORLD_LAND: readonly string[] = ${JSON.stringify(paths)};
`;
writeFileSync(join(root, "src", "ui", "worldLand.ts"), out);
console.log(`${paths.length} rings, ${pointCount} points, ${(out.length / 1024).toFixed(0)} KB`);
